def copy_clean(src: Path, dst: Path):
    """Copy a log or plan into the evidence with the machine-specific repo path replaced."""
    dst.write_text(src.read_text().replace(REPO_ROOT.as_uri(), "<repo>").replace(str(REPO_ROOT), "<repo>"))


def md_table(rows: list, columns: list) -> str:
    def fmt(v):
        if v is None:
            return ""
        if isinstance(v, float):
            return f"{v:,.4f}".rstrip("0").rstrip(".")
        if isinstance(v, int) and not isinstance(v, bool):
            return f"{v:,}"
        return str(v).replace("|", "\\|")
    out = ["| " + " | ".join(columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    out += ["| " + " | ".join(fmt(r.get(c)) for c in columns) + " |" for r in rows]
    return "\n".join(out)


def header(title: str) -> str:
    when = datetime.now(timezone.utc).isoformat(timespec="seconds")
    return f"# {title}\n\nGenerated by `python -m pipeline.evidence` on {when}. Do not edit by hand.\n\n"


def summaries(logs: Path) -> list:
    out = []
    for path in sorted(logs.glob("*.json")):
        try:
            data = json.loads(path.read_text())
        except json.JSONDecodeError:
            continue
        if "run_id" in data and "stages" in data:
            out.append(data)
    return out


def full_runs(logs: Path) -> list:
    return [s for s in summaries(logs) if s["requested_stages"] == DEFAULT_ORDER and s["status"] == "ok"]


def stage_metrics(summary: dict, name: str) -> dict:
    return next((s["metrics"] for s in summary["stages"] if s["stage"] == name), {})


