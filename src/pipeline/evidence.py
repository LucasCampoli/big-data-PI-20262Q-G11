def inventory(spark, cfg: Config) -> str:
    rows = []
    for zone, entity, path in lake.tables(cfg.datalake):
        if not lake.exists(path):
            continue
        stats = lake.table_stats(path)
        rows.append({"zone": zone, "table": entity, "path": str(path.relative_to(REPO_ROOT)),
                     "rows": lake.read(spark, path).count(), **stats,
                     "avg_file_kb": round(stats["bytes"] / stats["files"] / 1024, 1)})
    total = sum(r["bytes"] for r in rows)
    return (header("Data Lake inventory") + "Every table under `datalake/`, Parquet with Snappy. "
            "`partitions` counts partition directories (0 means unpartitioned).\n\n"
            + md_table(rows, ["zone", "table", "path", "rows", "files", "partitions", "bytes", "avg_file_kb"])
            + f"\n\nTotal: {total:,} bytes in {sum(r['files'] for r in rows)} files.\n")


