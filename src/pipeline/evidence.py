def cassandra_counts(cfg: Config) -> dict:
    if cfg.serving_target == "none":
        return {"status": "skipped"}
    try:
        settings = connection_settings(cfg)
        cluster, session = connect(settings)
    except Exception as exc:
        return {"status": f"unavailable: {exc}"}
    try:
        out = {"status": "ok", "target": settings["target"]}
        for table, _ in TABLES.values():
            orgs = [r.org_id for r in session.execute(f"SELECT DISTINCT org_id FROM {settings['keyspace']}.{table}")]
            stmt = session.prepare(f"SELECT COUNT(*) AS n FROM {settings['keyspace']}.{table} WHERE org_id = ?")
            out[table] = {"partitions": len(orgs), "rows": sum(session.execute(stmt, [o]).one().n for o in orgs)}
        return out
    finally:
        cluster.shutdown()


def snapshot(spark, cfg: Config, label: str) -> Path:
    tables = {f"{zone}/{entity}": lake.read(spark, path).count()
              for zone, entity, path in lake.tables(cfg.datalake) if lake.exists(path)}
    runs = full_runs(cfg.logs)
    data = {"label": label, "taken_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "last_full_run": runs[-1]["run_id"] if runs else None,
            "lake_rows": tables, "cassandra": cassandra_counts(cfg),
            "registry_files": lake.read(spark, cfg.registry).count() if lake.exists(cfg.registry) else 0,
            "checkpoint_commits": {q.name: len(list((q / "commits").glob("[0-9]*")))
                                   for q in sorted((cfg.datalake / "_checkpoints").glob("*")) if q.is_dir()}}
    cfg.evidence.mkdir(parents=True, exist_ok=True)
    path = cfg.evidence / f"counts_{label}.json"
    path.write_text(json.dumps(data, indent=2) + "\n")
    log.info("snapshot %s: %s", label, path)
    return path


