def data_dictionary(spark, cfg: Config) -> str:
    text = (header("Data dictionary") + "Schema of every table as stored in Parquet, read back from the lake. "
            "Partition columns are marked. Business descriptions of the source columns are in "
            "`docs/design.md` §3; technical and derived columns are described here.\n\n")
    for zone, entity, path in lake.tables(cfg.datalake):
        if not lake.exists(path):
            continue
        part_cols = {d.name.split("=")[0] for d in path.iterdir() if d.is_dir() and "=" in d.name}
        fields = lake.read(spark, path).schema.fields
        rows = [{"column": f.name + (" (partition)" if f.name in part_cols else ""),
                 "type": f.dataType.simpleString(), "note": COLUMN_NOTES.get(f.name, "")} for f in fields]
        text += f"## {zone}/{entity}\n\n" + md_table(rows, ["column", "type", "note"]) + "\n\n"
    return text


def quarantine_report(spark, cfg: Config) -> str:
    text = header("Quarantine samples")
    for title, root in (("Real Landing (`data/landing/`)", cfg.datalake),
                        ("Fixture Landing (`tests/fixtures/landing/`, D10)", REPO_ROOT / FIXTURE_LAKE)):
        text += f"## {title}\n\n"
        written = [(e, p) for z, e, p in lake.tables(root) if z == "quarantine"]
        text += md_table([{"table": f"quarantine/{e}", "rows": lake.read(spark, p).count() if lake.exists(p) else 0}
                          for e, p in written], ["table", "rows"]) + "\n\n"
        tables = [(e, lake.read(spark, p)) for e, p in written if lake.exists(p)]
        if not tables:
            text += "No quarantined rows: every record parsed and passed the rejection rules.\n\n"
            continue
        df = tables[0][1]
        for _, other in tables[1:]:
            df = df.unionByName(other)
        if df.count() == 0:
            text += "No quarantined rows: every record parsed and passed the rejection rules.\n\n"
            continue
        by_rule = [r.asDict() for r in df.groupBy("entity", "rule_name").count().orderBy("entity", "rule_name").collect()]
        text += "Rows by rule:\n\n" + md_table(by_rule, ["entity", "rule_name", "count"]) + "\n\nOne sample per rule:\n\n"
        w = Window.partitionBy("entity", "rule_name").orderBy("raw_record")
        samples = [r.asDict() for r in df.withColumn("_n", F.row_number().over(w)).filter("_n = 1")
                   .orderBy("entity", "rule_name").collect()]
        for s in samples:
            text += f"- `{s['entity']}` / `{s['rule_name']}` from `{s['source_file']}`:\n\n  ```\n  {s['raw_record']}\n  ```\n"
        text += "\n"
    return text


def stream_report(spark, cfg: Config) -> str:
    text = header("Streaming to Bronze")
    stream_runs = [(s, stage_metrics(s, "bronze-stream")) for s in summaries(cfg.logs)
                   if stage_metrics(s, "bronze-stream")]
    for title, pick in (("First ingestion", lambda s, m: m["bronze_usage_events"]["input_rows"] > 0
                         and s["config"]["stream_watermark"] == "1 hour"),
                        ("Rerun with the same checkpoint", lambda s, m: m["bronze_usage_events"]["input_rows"] == 0),
                        ("Experiment: 2 second watermark (`make stream-state-demo`)",
                         lambda s, m: s["config"]["stream_watermark"] == "2 seconds")):
        chosen = [(s, m) for s, m in stream_runs if pick(s, m)]
        if not chosen:
            continue
        s, m = chosen[-1]
        progress_path = cfg.logs / m["progress_file"]
        progress = [json.loads(l) for l in progress_path.read_text().splitlines()] if progress_path.exists() else []
        rows = []
        for p in progress:
            st = (p.get("stateOperators") or [{}])[0]
            rows.append({"query": p["name"], "batch": p["batchId"], "input_rows": p["numInputRows"],
                         "duration_ms": p["durationMs"].get("triggerExecution"),
                         "state_rows": st.get("numRowsTotal"), "state_rows_removed": st.get("numRowsRemoved"),
                         "dropped_by_watermark": st.get("numRowsDroppedByWatermark"),
                         "watermark": p.get("eventTime", {}).get("watermark")})
        text += (f"## {title}\n\nRun `{s['run_id']}`, watermark `{s['config']['stream_watermark']}` on "
                 f"`ingest_ts`, `maxFilesPerTrigger={s['config']['stream_max_files_per_trigger']}`, "
                 f"trigger `{s['config']['stream_trigger']}`. Progress file: `{m['progress_file']}`.\n\n"
                 + md_table([{"query": q, **v} for q, v in m.items() if isinstance(v, dict)],
                            ["query", "batches", "batches_with_data", "input_rows", "max_state_rows",
                             "state_rows_removed", "rows_dropped_by_watermark"])
                 + "\n\nPer micro-batch:\n\n"
                 + md_table(rows, ["query", "batch", "input_rows", "duration_ms", "state_rows",
                                   "state_rows_removed", "dropped_by_watermark", "watermark"]) + "\n\n")
    bronze_path = cfg.table("bronze", "usage_events")
    if lake.exists(bronze_path):
        b = lake.read(spark, bronze_path)
        per_file = b.groupBy("source_file").agg(F.max("timestamp").alias("max_ts"))
        w = Window.orderBy("source_file").rowsBetween(Window.unboundedPreceding, -1)
        seen = per_file.withColumn("prev_max", F.max("max_ts").over(w)).select("source_file", "prev_max")
        joined = b.join(seen, "source_file")
        late = []
        for days in (1, 7, 30):
            n = joined.filter(F.col("timestamp") < F.col("prev_max") - F.expr(f"INTERVAL {days} DAYS")).count()
            late.append({"event_time_watermark": f"{days} day(s)", "late_events": n,
                         "late_pct": round(100 * n / b.count(), 1), "kept_in_bronze": "yes"})
        text += ("## Late data\n\nReplaying the parts in file-name order, the events an event-time "
                 "watermark would have called late. Bronze keeps all of them because its watermark is "
                 f"on `ingest_ts`; Silver places each in its `event_date` partition. Bronze holds "
                 f"{b.count():,} events.\n\n"
                 + md_table(late, ["event_time_watermark", "late_events", "late_pct", "kept_in_bronze"]) + "\n")
    return text


def quality_report(cfg: Config) -> str:
    runs = [s for s in summaries(cfg.logs) if stage_metrics(s, "silver").get("usage_events")]
    if not runs:
        return header("Silver quality") + "No Silver run found.\n"
    s = runs[-1]
    m = stage_metrics(s, "silver")
    ev = m["usage_events"]
    rules = [
        {"rule": "event_id not null", "measure": "event_id_null in Silver", "value": ev["event_id_null"]},
        {"rule": "event_id unique", "measure": "silver_rows - distinct event_id", "value": ev["silver_rows"] - ev["distinct_event_id"]},
        {"rule": "cost_usd_increment >= -0.01, else flag", "measure": "rows with cost_anomaly_flag", "value": ev["cost_anomaly_flag"]},
        {"rule": "unit not null when value is present", "measure": "rows with value and no unit", "value": ev["value_without_unit"]},
        {"rule": "unit imputed from metric", "measure": "rows with unit_imputed", "value": ev["unit_imputed"]},
        {"rule": "null value stays null", "measure": "rows with value_double null", "value": ev["value_null"]},
    ]
    o3 = [{"measure": "quarantined events", "value": ev["quarantined_rows"], "pct": ev["quarantined_rows_pct"], "threshold_pct": 1.0},
          {"measure": "quarantined cost (USD)", "value": round(ev["quarantined_cost"], 4), "pct": ev["quarantined_cost_pct"], "threshold_pct": 1.0}]
    masters = [{"entity": e, **v} for e, v in m.items() if e != "usage_events"]
    flag_cols = sorted({k for v in masters for k in v if k not in ("entity", "rows", "quarantined")})
    return (header("Silver quality") + f"Run `{s['run_id']}`. Bronze events: {ev['bronze_rows']:,}, Silver events: "
            f"{ev['silver_rows']:,}, duplicates removed: {ev['duplicates_removed']:,}, event dates: {ev['event_dates']}.\n\n"
            "## Event rules required by the consigna\n\n" + md_table(rules, ["rule", "measure", "value"])
            + f"\n\nAfter imputation, every one of the {ev['silver_rows'] - ev['value_null']:,} Silver rows with a "
            f"value has a unit: the consigna rule holds at {100 * (1 - ev['value_without_unit'] / max(ev['silver_rows'] - ev['value_null'], 1)):.0f}%.\n\n"
            "## O3, Quarantine as an exception\n\n" + md_table(o3, ["measure", "value", "pct", "threshold_pct"])
            + "\n\nRejected events by rule: " + (json.dumps(ev["quarantined_by_rule"]) if ev["quarantined_by_rule"] else "none")
            + ".\n\n## Masters\n\n" + md_table(masters, ["entity", "rows", "quarantined"] + flag_cols) + "\n")


def detection_text(check) -> str:
    if not check:
        return ""
    cols = ["org_id", "usage_date", "service", "daily_cost_usd", "median_cost", "history_days",
            "score_method", "anomaly_score"]
    rows = [{"days": label, "count": check[k]["days"], "flagged": check[k]["flagged"],
             "flagged_pct": check[k]["flagged_pct"], "not_flagged_scored": check[k]["not_flagged_scored"],
             "not_flagged_unscored": check[k]["not_flagged_unscored"]}
            for k, label in (("above_p99", f"daily cost above the p99 ({check['daily_cost_p99_usd']} USD)"),
                             ("negative", "negative daily cost"))]
    text = ("\n\n### Detection check\n\nWithout labels, the days a fixed threshold would call extreme are the "
            "reference: how many the relative method flags, and why it leaves the rest.\n\n"
            + md_table(rows, ["days", "count", "flagged", "flagged_pct", "not_flagged_scored", "not_flagged_unscored"]))
    for k, label in (("above_p99", "Above the p99"), ("negative", "Negative daily cost")):
        text += (f"\n\n{label}, flagged:\n\n" + md_table(check[k]["flagged_examples"], cols)
                 + f"\n\n{label}, not flagged:\n\n" + md_table(check[k]["not_flagged_examples"], cols))
    return text


