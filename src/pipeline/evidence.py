def profile_rows(cfg: Config, run: dict):
    app = run.get("spark_app_id")
    path = cfg.logs / "spark-events" / app if app else None
    if not path or not path.exists():
        return None
    jobs, stages = {}, {}
    for line in path.read_text().splitlines():
        e = json.loads(line)
        if e["Event"] == "SparkListenerJobStart":
            props = e.get("Properties") or {}
            # Streaming micro-batches run in the query's own thread, tagged by query id.
            group = "bronze-stream" if props.get("sql.streaming.queryId") else props.get("spark.jobGroup.id", "other")
            jobs[e["Job ID"]] = group
            for sid in e.get("Stage IDs", []):
                stages.setdefault(sid, {"group": group})
        elif e["Event"] == "SparkListenerStageCompleted":
            si = e["Stage Info"]
            acc = {a["Name"]: int(a.get("Value") or 0) for a in si.get("Accumulables", [])
                   if str(a.get("Value", "")).lstrip("-").isdigit()}
            stages.setdefault(si["Stage ID"], {"group": "other"}).update(
                tasks=si["Number of Tasks"], completed=True,
                run_ms=acc.get("internal.metrics.executorRunTime", 0),
                input_bytes=acc.get("internal.metrics.input.bytesRead", 0),
                shuffle_write=acc.get("internal.metrics.shuffle.write.bytesWritten", 0))
    seconds = {st["stage"]: st["seconds"] for st in run["stages"]}
    rows = []
    for name in run["requested_stages"]:
        sts = [s for s in stages.values() if s["group"] == name and s.get("completed")]
        rows.append({"pipeline_stage": name, "wall_s": seconds.get(name),
                     "spark_jobs": sum(1 for g in jobs.values() if g == name),
                     "spark_stages": len(sts), "tasks": sum(s["tasks"] for s in sts),
                     "executor_run_s": round(sum(s["run_ms"] for s in sts) / 1000, 1),
                     "input_kb": round(sum(s["input_bytes"] for s in sts) / 1024, 1),
                     "shuffle_write_kb": round(sum(s["shuffle_write"] for s in sts) / 1024, 1)})
    return rows


def execution_profile(cfg: Config, runs: list) -> str:
    c = runs[0]["config"]
    text = (header("Execution profile") + f"Master `{c['spark_master']}`, driver memory `{c['driver_memory']}`, "
            f"`spark.sql.shuffle.partitions={c['shuffle_partitions']}`, adaptive query execution on. From the Spark "
            "event log of each run, grouped by the job group each pipeline stage sets. `input_kb` counts every "
            "read Spark reports, including cached partitions read back from memory and the re-reads that compute "
            "the run metrics; the streaming stage reads the 13 MB of JSON once per query.\n\n")
    for i, run in enumerate(runs, 1):
        rows = profile_rows(cfg, run)
        title = "first ingestion" if i == 1 else "rerun, nothing new to ingest"
        text += f"## Run {i}, {title}\n\nRun `{run['run_id']}`, Spark app `{run.get('spark_app_id')}`.\n\n"
        text += (md_table(rows, ["pipeline_stage", "wall_s", "spark_jobs", "spark_stages", "tasks",
                                 "executor_run_s", "input_kb", "shuffle_write_kb"]) if rows else "Event log not found.") + "\n\n"
    return text


def idempotency_report(cfg: Config) -> str:
    snaps = {p.stem.removeprefix("counts_"): json.loads(p.read_text()) for p in sorted(cfg.evidence.glob("counts_*.json"))}
    if not {"run_1", "run_2"} <= set(snaps):
        return header("Idempotency") + "Needs counts_run_1.json and counts_run_2.json (make rerun-evidence).\n"
    a, b = snaps["run_1"], snaps["run_2"]
    rows = [{"table": t, "after_run_1": a["lake_rows"].get(t), "after_run_2": b["lake_rows"].get(t),
             "same": a["lake_rows"].get(t) == b["lake_rows"].get(t)} for t in sorted(set(a["lake_rows"]) | set(b["lake_rows"]))]
    for table, _ in TABLES.values():
        ra, rb = (a["cassandra"].get(table) or {}).get("rows"), (b["cassandra"].get(table) or {}).get("rows")
        rows.append({"table": f"cassandra/{table}", "after_run_1": ra, "after_run_2": rb, "same": ra == rb})
    rows.append({"table": "_registry/ingested_files", "after_run_1": a["registry_files"],
                 "after_run_2": b["registry_files"], "same": a["registry_files"] == b["registry_files"]})
    ok = all(r["same"] for r in rows)
    checkpoints = [{"query": q, "commits_after_run_1": a["checkpoint_commits"].get(q),
                    "commits_after_run_2": b["checkpoint_commits"].get(q)} for q in sorted(b["checkpoint_commits"])]
    return (header("Idempotency: the full pipeline twice in a row") +
            f"Run 1: `{a['last_full_run']}` on a reset lake and empty Cassandra tables. Run 2: `{b['last_full_run']}`, "
            "same inputs, nothing reset in between.\n\n" + md_table(rows, ["table", "after_run_1", "after_run_2", "same"])
            + f"\n\nAll counts equal: **{ok}**.\n\nStreaming checkpoints, committed micro-batches:\n\n"
            + md_table(checkpoints, ["query", "commits_after_run_1", "commits_after_run_2"])
            + "\n\nRun 2 reads no new event part (the checkpoint already lists all of them), skips the seven "
            "registered CSVs, rebuilds Silver and Gold over the same partitions and upserts the same "
            "Cassandra keys.\n")


def copy_run_logs(cfg: Config):
    runs = full_runs(cfg.logs)[-2:]
    for i, run in enumerate(runs, 1):
        for ext in ("log", "json"):
            src = cfg.logs / f"{run['run_id']}.{ext}"
            if src.exists():
                copy_clean(src, cfg.evidence / f"run_{i}_{run['run_id']}.{ext}")
        progress = stage_metrics(run, "bronze-stream").get("progress_file")
        if progress and (cfg.logs / progress).exists():
            copy_clean(cfg.logs / progress, cfg.evidence / f"run_{i}_stream_progress.jsonl")
    fixture_runs = full_runs(REPO_ROOT / FIXTURE_LOGS) or summaries(REPO_ROOT / FIXTURE_LOGS)
    if fixture_runs:
        src = REPO_ROOT / FIXTURE_LOGS / f"{fixture_runs[-1]['run_id']}.log"
        if src.exists():
            copy_clean(src, cfg.evidence / "fixtures_run.log")
    demo = [s for s in summaries(cfg.logs) if s["config"]["stream_watermark"] == "2 seconds"]
    if demo:
        progress = stage_metrics(demo[-1], "bronze-stream").get("progress_file")
        if progress and (cfg.logs / progress).exists():
            copy_clean(cfg.logs / progress, cfg.evidence / "stream_state_demo_progress.jsonl")
    return runs


def report(spark, cfg: Config):
    cfg.evidence.mkdir(parents=True, exist_ok=True)
    for old in cfg.evidence.glob("run_*"):
        old.unlink()
    runs = copy_run_logs(cfg)
    files = {
        "lake_inventory.md": inventory(spark, cfg),
        "data_dictionary.md": data_dictionary(spark, cfg),
        "quarantine_samples.md": quarantine_report(spark, cfg),
        "stream_bronze.md": stream_report(spark, cfg),
        "silver_quality.md": quality_report(cfg),
        "gold_marts.md": gold_report(cfg),
        "idempotency.md": idempotency_report(cfg),
    }
    if runs:
        files["execution_profile.md"] = execution_profile(cfg, runs)
    for name, text in files.items():
        if text:
            (cfg.evidence / name).write_text(text)
            log.info("wrote %s", cfg.evidence / name)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["snapshot", "report"])
    parser.add_argument("label", nargs="?")
    args = parser.parse_args(argv)
    cfg = Config.from_env()
    run_id = new_run_id()
    # Evidence runs log in their own folder so they never count as a pipeline run.
    own = dataclasses.replace(cfg, logs=cfg.logs / "evidence")
    setup_logging(own, run_id)
    spark = build_session(own, f"evidence-{run_id}")
    try:
        if args.command == "snapshot":
            if not args.label:
                parser.error("snapshot needs a label")
            snapshot(spark, cfg, args.label)
        else:
            report(spark, cfg)
    finally:
        spark.stop()
    return 0


if __name__ == "__main__":
    sys.exit(main())
